DO $validation$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM launches launch
    LEFT JOIN launch_timezone_import mapping ON mapping.source_id = launch.id
    WHERE mapping.source_id IS NULL
  ) THEN
    RAISE EXCEPTION 'The timezone mapping does not cover every launch.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM launch_timezone_import mapping
    LEFT JOIN pg_timezone_names timezone ON timezone.name = mapping.timezone
    WHERE timezone.name IS NULL
  ) THEN
    RAISE EXCEPTION 'The timezone mapping contains a name PostgreSQL does not recognize.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM launches
    WHERE latitude NOT BETWEEN -90 AND 90
       OR longitude NOT BETWEEN -180 AND 180
  ) THEN
    RAISE EXCEPTION 'A launch has invalid latitude or longitude.';
  END IF;
END
$validation$;

UPDATE arenas arena
SET
  name = launch.name,
  country = launch.country,
  state = launch.state,
  city = launch.city,
  location = ST_SetSRID(ST_MakePoint(launch.longitude, launch.latitude), 4326),
  altitude_meters = launch.elevation,
  timezone = mapping.timezone
FROM launches launch
INNER JOIN launch_timezone_import mapping ON mapping.source_id = launch.id
WHERE arena.source_id = launch.id
  AND arena.definition_type = 'grid';

COMMIT;
